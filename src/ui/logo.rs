const FROM: (u8, u8, u8) = (0, 212, 255);
const TO: (u8, u8, u8) = (178, 102, 255);
const SHADOW: f32 = 0.45;

pub fn pick(max_w: usize, max_h: usize) -> &'static Logo {
    [&WIDE, &DOUBLE, &STACKED]
        .into_iter()
        .find(|logo| logo.width() <= max_w && logo.height() <= max_h)
        .unwrap_or(&COMPACT)
}

pub fn supports_truecolor() -> bool {
    std::env::var("COLORTERM").is_ok_and(|v| v == "truecolor" || v == "24bit")
}

impl Logo {
    pub fn width(&self) -> usize {
        self.lines.iter().map(|l| l.chars().count()).max().unwrap_or(0)
    }

    pub fn height(&self) -> usize {
        self.lines.len()
    }

    pub fn draw(&self, out: &mut impl Write, x: u16, y: u16, truecolor: bool) -> io::Result<()> {
        let last = self.width().saturating_sub(1).max(1) as f32;

        for (row, line) in self.lines.iter().enumerate() {
            queue!(out, MoveTo(x, y + row as u16))?;

            for (col, ch) in line.chars().enumerate() {
                if ch == ' ' {
                    queue!(out, Print(' '))?;
                    continue;
                }
                let shadow = self.shaded && ch != '█';
                let color = if truecolor {
                    let t = col as f32 / last;
                    let k = if shadow { SHADOW } else { 1.0 };
                    Color::Rgb {
                        r: mix(FROM.0, TO.0, t, k),
                        g: mix(FROM.1, TO.1, t, k),
                        b: mix(FROM.2, TO.2, t, k),
                    }
                } else if shadow {
                    Color::DarkCyan
                } else {
                    Color::Cyan
                };
                queue!(out, SetForegroundColor(color), Print(ch))?;
            }
        }
        queue!(out, ResetColor)
    }
}

fn mix(a: u8, b: u8, t: f32, k: f32) -> u8 {
    ((a as f32 + (b as f32 - a as f32) * t) * k).round() as u8
}

